import json
import unittest
from datetime import date

from helpers import D0, D1, build_all, build_new_map  # noqa: F401
from kstock.engine import (
    evaluate_new_map,
    is_complete,
    reconstruct_holding,
    record_decision,
    snapshot_hash,
    snapshot_to_holding,
    validate,
)
from kstock.models import Decision, MarketState, Position, Scenario, load_map
from kstock.templates import new_map_skeleton


class TestNewMap(unittest.TestCase):
    def test_skeleton_is_incomplete_and_demo_is_complete(self):
        sk = new_map_skeleton("000000", "X", "growth", D0)
        self.assertFalse(is_complete(sk, D0))
        a = build_new_map()
        self.assertTrue(is_complete(a, D0), [str(i) for i in validate(a, D0)])

    def test_rr_gate_forces_watch(self):
        a = build_new_map()
        a["A0.4"].set(62000, as_of=D0)  # RR = (85-62)/(62-48) = 1.64 < 2.0
        res = evaluate_new_map(a, today=D0)
        self.assertFalse(res.rr_gate_passed)
        self.assertEqual(a.decision, Decision.WATCH)
        self.assertTrue(any("WATCH 강제" in n for n in res.notes))

    def test_probability_sum_error(self):
        a = build_new_map()
        a["A4.4"].scenario = Scenario(name="Bull", probability=0.5, target_price=120000)
        errs = [i for i in validate(a, D0) if i.level == "error"]
        self.assertTrue(any("확률 합" in i.message for i in errs))

    def test_json_roundtrip_preserves_sub_schemas(self):
        a = build_new_map()
        a2 = load_map(json.loads(a.to_json()))
        self.assertEqual(a2["A1.1"].driver.my_estimate.value, 13.0)
        self.assertEqual(a2["A4.3"].scenario.target_price, 85000)
        self.assertEqual(a2["A5.4.1"].rule.condition, "driver[A1.2].current < 3500")


class TestSnapshot(unittest.TestCase):
    def test_snapshot_copies_and_is_immutable(self):
        a = build_new_map()
        pos = Position(entry_date=D0, entry_price=58000, quantity=100, w_target=0.05)
        b = snapshot_to_holding(a, pos, today=D0)
        self.assertEqual(b.value("B1.1"), a.thesis)
        self.assertEqual(b["B2.1.1"].driver.at_entry, 8.1)
        self.assertEqual(b.value("B1.5"), "기록")
        self.assertEqual(b["B1.6"].links, ["S.KR-ROBOT", "M0"])
        self.assertEqual(len(b.children("B1.4")), 1)
        self.assertEqual(snapshot_hash(b), b.snapshot_hash)
        # 스냅숏 수정 → 검증 오류
        b["B1.1"].value = "다른 논제"
        errs = [i for i in validate(b, D0) if i.level == "error"]
        self.assertTrue(any("불변" in i.message for i in errs))

    def test_weight_band_rule_autogenerated(self):
        a = build_new_map()
        b = snapshot_to_holding(a, Position(entry_date=D0, entry_price=58000, quantity=100, w_target=0.05), today=D0)
        conds = [n.rule.condition for n in b.rules()]
        self.assertIn("w_now > 0.0650", conds)


class TestReconstruct(unittest.TestCase):
    def test_no_thesis_is_flagged(self):
        pos = Position(entry_date=date(2025, 3, 1), entry_price=10000, quantity=500, w_target=0.04)
        b = reconstruct_holding("111111", "무논제", pos, invest_type=None, thesis=None, today=D1,
                                market=MarketState(as_of=D1, price=9000, w_now=0.035))
        self.assertTrue(b.no_thesis)
        from kstock.engine import evaluate_holding
        r = evaluate_holding(b, today=D1)
        self.assertEqual(r.light.light.value, "YELLOW")
        self.assertIn("논제 없는 보유", r.light.reasons)
        self.assertEqual(r.matrix.action.value, "review")

    def test_reconstructed_with_drivers(self):
        pos = Position(entry_date=date(2025, 3, 1), entry_price=10000, quantity=500, w_target=0.04)
        b = reconstruct_holding("222222", "복원", pos, invest_type="value", thesis="저평가 + 배당",
                                drivers=[{"label": "배당수익률", "current": 5.5, "my_estimate": 6.0, "at_entry": 5.0}],
                                kill_conditions=["driver[B2.1.1].current < 3"], today=D1)
        self.assertEqual(b.value("B1.5"), "재구성")
        self.assertEqual(b["B2.1.1"].driver.direction.value, "강화")
        self.assertEqual(len(b.children("B1.4")), 1)


class TestDecisionLog(unittest.TestCase):
    def test_override_requires_reason(self):
        a, b, c, rep = build_all()
        b.meta["matrix_default"] = "trim"
        with self.assertRaises(ValueError):
            record_decision(b, "add", today=D1, reason="")
        log = record_decision(b, "add", today=D1, reason="실적 발표 전 선취매")
        self.assertTrue(log.override)
        self.assertEqual(b.value("B6"), "add")

    def test_pnl_never_feeds_judgment(self):
        a, b, c, rep = build_all()
        self.assertTrue(b["B0.5"].meta_only)
        b["B6"].links = ["B0.5"]
        errs = [i for i in validate(b, D1) if i.level == "error"]
        self.assertTrue(any("meta_only" in i.message for i in errs))


if __name__ == "__main__":
    unittest.main()
